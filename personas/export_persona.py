if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    sys.stderr.reconfigure(encoding='utf-8', errors='replace')

TARGETS = ('claude', 'codex', 'gemini', 'opencode', 'hermes', 'generic')


def load_validator(p_root):
    spec = importlib.util.spec_from_file_location('office_validate_persona', p_root / 'validate_persona.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def extract_title_and_summary(persona_md_text, persona_id):
    title_m = re.search(r'(?m)^#\s+(.+?)\s*(?:\(`[^`]+`\))?\s*$', persona_md_text)
    role_title = title_m.group(1).strip() if title_m else persona_id.replace('-', ' ').title()
    role_sec = re.search(r'## Role & Identity\s+(.+?)(?=\n## |\Z)', persona_md_text, re.S)
    first_sentence = ''
    if role_sec:
        clean = ' '.join(role_sec.group(1).strip().split())
        first_sentence = clean[:220]
    desc = f'{role_title} specialist persona for Office AI. {first_sentence}'.strip()
    return role_title, desc


def extract_approved_learnings(learnings_text):
    lines = []
    in_entries = False
    for line in learnings_text.splitlines():
        if line.strip().startswith('## Approved Entries'):
            in_entries = True
            continue
        if in_entries:
            lines.append(line)
    body = '\n'.join(lines).strip()
    if not body or 'No approved learnings recorded yet' in body:
        return '*(No approved learnings yet — approve recurring lessons in the Office AI Learning Cabinet first.)*'
    return body


